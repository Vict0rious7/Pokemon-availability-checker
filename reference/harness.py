"""Reference harness for the Pokémon availability checker rebuild (Phase 0, step 3).

Runs the OLD engine (pokecheck.computeAvailability, Streamlit version) on every
profile in profiles.json and saves its output, unchanged, as the reference the
new engine is compared against in Phase 1.

Usage
  python harness.py --engine-dir PATH            # run all profiles, write results/ and SUMMARY.md
  python harness.py --engine-dir PATH --check    # re-run and compare with the saved results (no writes)
  python harness.py --compare-dir OTHER          # compare saved results with another results dir (e.g. new engine)

PATH is a checkout of Vict0rious7/Pokemon-availability-checker, ideally at the
commit pinned in profiles.json. Exit code is 1 when a comparison finds differences.
"""
import argparse
import contextlib
import importlib
import inspect
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROFILES = HERE / "profiles.json"
RESULTS = HERE / "results"
SUMMARY = HERE / "SUMMARY.md"

COUNT_PARAMS = ("gb_gbc_number", "gba_number", "ds_number", "three_ds_number", "switch_number")
LANGUAGE_PARAMS = ("bonus_disc_language", "ranch_language", "battle_rev_language")


@contextlib.contextmanager
def cwd(path):
    old = os.getcwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(old)


def load_engine(engine_dir):
    """Import pokecheck from engine_dir. The engine opens its CSVs by relative path."""
    sys.path.insert(0, str(engine_dir))
    module = importlib.import_module("pokecheck")
    return module.computeAvailability


def engine_commit(engine_dir):
    try:
        return subprocess.run(["git", "-C", str(engine_dir), "rev-parse", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def resolve_inputs(spec, param_names):
    """Turn a profile's inputs into the full keyword set, mirroring the UI's defaults:
    flags off, languages None, counts '0'. 'ALL' mirrors the Finder tab."""
    if spec == "ALL":
        return {p: ("2+" if p in COUNT_PARAMS else "Both" if p in LANGUAGE_PARAMS else True)
                for p in param_names}
    unknown = set(spec) - set(param_names)
    if unknown:
        raise ValueError(f"unknown input(s) {sorted(unknown)}; valid names are the engine's parameters")
    resolved = {p: ("0" if p in COUNT_PARAMS else None if p in LANGUAGE_PARAMS else False)
                for p in param_names}
    resolved.update(spec)
    return resolved


def clean_name(name):
    return " ".join(name.split())  # form names contain a line break inside the CSV cell


def run_profile(compute, engine_dir, profile, param_names):
    inputs = resolve_inputs(profile["inputs"], param_names)
    with cwd(engine_dir):
        available, unavailable = compute(**inputs)
    rows_available = [{"number": n, "name": clean_name(name),
                       "games": [g.strip() for g in games.strip("[]").split(",") if g.strip()]}
                      for n, name, games in available]
    rows_unavailable = [{"number": n, "name": clean_name(name)} for n, name in unavailable]
    return inputs, rows_available, rows_unavailable


def as_map(result):
    """Row key -> sorted, de-duplicated games ([] for unavailable). Order-insensitive, for comparisons.
    De-duplication matters: the old gen 5 function can list 'Dream Radar' twice (no dict.fromkeys)."""
    out = {f"{r['number']} {r['name']}": sorted(set(r["games"])) for r in result["available"]}
    out.update({f"{r['number']} {r['name']}": [] for r in result["unavailable"]})
    return out


def diff(reference, other):
    a, b = as_map(reference), as_map(other)
    lines = []
    for key in sorted(set(a) | set(b), key=lambda k: (int(k.split()[0]), k)):
        if key not in a:
            lines.append(f"  + {key}: only in other")
        elif key not in b:
            lines.append(f"  - {key}: only in reference")
        elif a[key] != b[key]:
            lines.append(f"  ~ {key}: reference {a[key] or 'unavailable'} | other {b[key] or 'unavailable'}")
    return lines


def probe_rows(result, probe):
    """Rows whose name is the probe or a form of it ('Weezing' also matches 'Weezing (Galarian Form)')."""
    rows = [(r["name"], ", ".join(r["games"])) for r in result["available"]
            if r["name"] == probe or r["name"].startswith(probe + " (")]
    rows += [(r["name"], "not obtainable") for r in result["unavailable"]
             if r["name"] == probe or r["name"].startswith(probe + " (")]
    return rows or [(probe, "NO SUCH ROW: check the probe name")]


def write_summary(results, commit):
    out = ["# Reference results: old engine",
           "",
           f"Engine commit `{commit}`. Generated by `harness.py`; do not edit by hand.",
           "Mark a known wrong answer by adding it to the profile's `known_wrong` in profiles.json.",
           "",
           "| Profile | Kind | Description | Available | Unavailable |",
           "| --- | --- | --- | --- | --- |"]
    for r in results:
        p = r["profile"]
        out.append(f"| {p['id']} | {p['kind']} | {p['description']} | {r['counts']['available']} | {r['counts']['unavailable']} |")
    for r in results:
        p = r["profile"]
        out += ["", f"## {p['id']} — {p['description']}", "",
                f"Exercises: {'; '.join(p['exercises'])}", "",
                "| Probe | Games the old engine credits |", "| --- | --- |"]
        for probe in p["probes"]:
            for name, games in probe_rows(r, probe):
                out.append(f"| {name} | {games} |")
        if p["known_wrong"]:
            out += ["", "Known wrong (Victor): " + "; ".join(
                f"{k['pokemon']} ({k.get('note', '')})" for k in p["known_wrong"])]
    SUMMARY.write_text("\n".join(out) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--engine-dir", type=Path, help="checkout of the old Streamlit repo")
    ap.add_argument("--check", action="store_true", help="re-run and compare with saved results, write nothing")
    ap.add_argument("--compare-dir", type=Path, help="compare saved results with results in this directory")
    args = ap.parse_args()
    config = json.loads(PROFILES.read_text(encoding="utf-8"))

    if args.compare_dir:
        failed = False
        for p in config["profiles"]:
            ref = json.loads((RESULTS / f"{p['id']}.json").read_text(encoding="utf-8"))
            other_path = args.compare_dir / f"{p['id']}.json"
            if not other_path.exists():
                print(f"{p['id']}: MISSING in {args.compare_dir}")
                failed = True
                continue
            d = diff(ref, json.loads(other_path.read_text(encoding="utf-8")))
            print(f"{p['id']}: {'identical' if not d else f'{len(d)} difference(s)'}")
            print("\n".join(d)) if d else None
            failed |= bool(d)
        sys.exit(1 if failed else 0)

    if not args.engine_dir:
        ap.error("--engine-dir is required unless --compare-dir is given")
    engine_dir = args.engine_dir.resolve()
    commit = engine_commit(engine_dir)
    if commit != config["engine_commit"]:
        print(f"WARNING: engine at {commit}, profiles pinned to {config['engine_commit']}")
    compute = load_engine(engine_dir)
    param_names = list(inspect.signature(compute).parameters)

    results, failed = [], False
    for p in config["profiles"]:
        inputs, available, unavailable = run_profile(compute, engine_dir, p, param_names)
        result = {"engine": {"repo": "Vict0rious7/Pokemon-availability-checker", "commit": commit},
                  "profile": {**{k: v for k, v in p.items() if k != "inputs"}, "inputs": inputs},
                  "counts": {"available": len(available), "unavailable": len(unavailable)},
                  "available": available, "unavailable": unavailable}
        path = RESULTS / f"{p['id']}.json"
        if args.check:
            d = diff(json.loads(path.read_text(encoding="utf-8")), result)
            print(f"{p['id']}: {'identical' if not d else f'{len(d)} difference(s)'}")
            print("\n".join(d)) if d else None
            failed |= bool(d)
        else:
            RESULTS.mkdir(exist_ok=True)
            path.write_text(json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
            print(f"{p['id']}: {len(available)} available, {len(unavailable)} unavailable")
        results.append(result)

    if args.check:
        sys.exit(1 if failed else 0)
    write_summary(results, commit)
    print(f"Wrote {len(results)} results and {SUMMARY.name}")


if __name__ == "__main__":
    main()
